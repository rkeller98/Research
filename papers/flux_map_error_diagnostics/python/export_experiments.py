"""Export the existing analyzers' results; no fitting, filtering or interpolation.

Python writes numeric tables and concrete PGFPlots drawings. The repository's
shared styles render vector graphics when the manuscript is built.
"""
from pathlib import Path
import hashlib
import importlib.metadata
import json
import numpy as np
import pandas as pd

from flux_correction import DEFAULT_HIGH_IQ_REL

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "figures" / "data" / "experimental"


def robust(values):
    values = np.asarray(values, dtype=float)
    median = float(np.median(values))
    return {"median": median, "raw_mad": float(np.median(abs(values - median))),
            "min": float(values.min()), "max": float(values.max())}


def save_dat(frame, filename):
    frame.to_csv(DATA / filename, sep=" ", index=False, float_format="%.12g",
                 na_rep="nan")


def figure(filename, body, caption, label):
    source = ("% Generated by python/export_experiments.py; do not edit manually.\n"
              "\\begin{figure}[p]\n\\centering\n\\begin{tikzpicture}\n" + body +
              "\n\\end{tikzpicture}\n\\caption{" + caption + "}\n\\label{" + label +
              "}\n\\end{figure}\n")
    (ROOT / "figures" / filename).write_text(source, encoding="utf-8")


def map_panel(filename, field, title, ylabel, limit):
    xlabel = r"$i_d$ / A" if "_flux" in filename else r"$i_{d,\mathrm{key}}$ / A"
    return (r"\nextgroupplot[sample map axis,width=.35\textwidth,height=4.8cm,title={" + title +
            r"},xlabel={" + xlabel + r"},ylabel={" + ylabel +
            f"}},point meta min={-limit:.12g},point meta max={limit:.12g}]\n" +
            r"\addplot[sample map] table[x=id_plot,y=iq_plot,meta=" + field +
            "]{figures/data/experimental/" + filename + "};\n")


def export_analysis(raw, analyzers, experiment, input_path, common=None):
    DATA.mkdir(parents=True, exist_ok=True)
    report = {"experiment": experiment, "dataset": input_path.name,
              "sha256": hashlib.sha256(input_path.read_bytes()).hexdigest(),
              "packages": {p: importlib.metadata.version(p) for p in
                           ("numpy", "pandas", "scipy", "h5py", "matplotlib")},
              "settings": {"pairing_decimals": analyzers[0].pairing_decimals,
                           "min_iq_rel_strict": analyzers[0].min_iq_rel,
                           "high_iq_rel_inclusive": DEFAULT_HIGH_IQ_REL,
                           "speed_source": "PE_Rpm_req"}, "slices": []}
    rpm_req = raw.get_signal("PE_Rpm_req")
    temp_ref = raw.get_signal("Rotor_temp_ref")
    files, tables = [], []
    for a in analyzers:
        m = a.measurement
        tag = f"{experiment}_{m.rpm:g}_{m.rotor_temperature:g}"
        mask = np.isclose(rpm_req, m.rpm) & np.isclose(temp_ref, m.rotor_temperature)
        points, pairs = a.flux_points.copy(), a.symmetric_pairs.copy()
        keys = points[["id_req", "iq_req"]].round(a.pairing_decimals).drop_duplicates()
        valid = pairs[pairs.valid_delta_R_eq].copy()
        high = valid[valid.iq_mag >= DEFAULT_HIGH_IQ_REL * valid.iq_mag.max()]
        estimate = a.estimate_high_current_resistance()
        summary = {"rpm": m.rpm, "rotor_reference_C": m.rotor_temperature,
                   "raw_samples": int(mask.sum()), "op_index_groups": len(points),
                   "unique_requested_keys": len(keys), "symmetric_pairs": len(pairs),
                   "valid_equivalent_pairs": len(valid), "high_current_pairs": len(high),
                   "unpaired_nonzero_keys": int((keys.iq_req != 0).sum()-2*len(pairs)),
                   "zero_q_keys": int((keys.iq_req == 0).sum()),
                   "pole_pairs": m.pole_pairs, "omega_e_rad_s": m.omega_e,
                   "used_resistance_ohm": m.stator_resistance,
                   "used_resistance_unique_count": len(np.unique(raw.get_signal("Const_Machine_R_s")[mask])),
                   "iq_max_A": float(pairs.iq_mag.max()),
                   "full_valid_equivalent_ohm": robust(valid.delta_R_eq),
                   "high_equivalent_ohm": robust(high.delta_R_eq),
                   "conditional_resistance_ohm": estimate.resistance_equivalent,
                   "symmetry_metrics_Wb": a.symmetry_metrics(),
                   "pair_id_difference_max_A": float(abs(pairs.id_pos-pairs.id_neg).max()),
                   "pair_iq_sum_max_A": float(abs(pairs.iq_pos+pairs.iq_neg).max())}
        # Additional signals are reported for traceability, never substituted
        # for the requested-speed breakpoint in the actual reconstruction.
        names = raw.get_signal_names()
        for name in ("PE_speed_rpm", "CAN_RPM_meas", "PE_Char_Temp_Stator_ref_DegCel"):
            if name in names:
                summary[name] = robust(raw.get_signal(name)[mask])
        report["slices"].append(summary)
        points.to_csv(DATA / f"{tag}_flux.csv", index=False)
        pairs.to_csv(DATA / f"{tag}_pairs.csv", index=False)
        plot_points = pd.DataFrame({"id_plot": points.id, "iq_plot": points.iq,
                                    "psi_d_mWb": 1e3*points.psi_d,
                                    "psi_q_mWb": 1e3*points.psi_q})
        plot_pairs = pd.DataFrame({"id_plot": pairs.id_key, "iq_plot": pairs.iq_mag,
                                   "relative_iq": pairs.iq_mag/pairs.iq_mag.max(),
                                   "rd_mWb": 1e3*pairs.r_d, "rq_mWb": 1e3*pairs.r_q,
                                   "req_mOhm": 1e3*pairs.delta_R_eq})
        save_dat(plot_points, f"{tag}_flux.dat")
        save_dat(plot_pairs, f"{tag}_pairs.dat")
        save_dat(plot_pairs[pairs.valid_delta_R_eq], f"{tag}_valid.dat")
        files.append(tag)
        tables.append(f"{m.rpm:.0f} & {m.rotor_temperature:.0f} & {len(points)} & "
                      f"{len(keys)} & {len(pairs)} & {len(valid)} & {len(high)} & "
                      f"{1e3*estimate.delta_R_eq_median:.3f} & "
                      f"{1e3*estimate.delta_R_eq_mad:.3f} \\\\")
    (DATA / f"{experiment}_summary.tex").write_text("\n".join(tables)+"\n", encoding="utf-8")
    # Either analyzer runs independently. Once both row exports exist, combine
    # them in one complete tabular to avoid noalign at TeX input boundaries.
    row_paths = [DATA / f"{name}_summary.tex" for name in ("outlier", "multi")]
    if all(p.is_file() for p in row_paths):
        table = (r"\begin{tabular}{@{}rrrrrrrrr@{}}"+"\n"+r"\toprule"+"\n"+
                 r"$n$ & $T_{\rm rot,ref}$ & $N_{\rm op}$ & $N_{\rm key}$ & $N_{\rm pair}$ & $N_{\rm valid}$ & $N_{\rm high}$ & Median & MAD\\"+"\n"+
                 r"rpm & $^\circ$C & & & & & & m$\Omega$ & m$\Omega$\\"+"\n"+
                 r"\midrule"+"\n"+row_paths[0].read_text(encoding="utf-8")+
                 r"\midrule"+"\n"+row_paths[1].read_text(encoding="utf-8")+
                 r"\bottomrule"+"\n"+r"\end{tabular}"+"\n")
        (DATA / "combined_summary.tex").write_text(table, encoding="utf-8")
    if experiment == "outlier":
        body = (r"\begin{groupplot}[group style={group size=2 by 3,horizontal sep=32mm,vertical sep=19mm},"
                r"width=.40\textwidth,height=4.8cm]" + "\n")
        for a, tag in zip(analyzers, files):
            for f, symbol in (("psi_d_mWb", r"\psi_d"), ("psi_q_mWb", r"\psi_q")):
                limit = max(float(abs(x.flux_points[f.replace("_mWb", "")]).max())*1e3
                            for x in analyzers)
                title = f"${a.measurement.rotor_temperature:g}$ " + r"$^\circ$C; $"+symbol+r"$ / mWb"
                body += map_panel(tag+"_flux.dat", f, title, r"$i_q$ / A", limit)
        figure("08_experimental_flux.tex", body+r"\end{groupplot}",
               r"Reconstructed measured flux samples at 2000 rpm. Columns show $\psi_d$ and $\psi_q$; rows show rotor references 40, 60 and 80 $^\circ$C. Color denotes flux in mWb with one fixed range per component across temperatures. Every operating-point mean is shown; no surface fit or interpolation is applied.", "fig:experimental-flux")
        body = (r"\begin{groupplot}[group style={group size=2 by 3,horizontal sep=32mm,vertical sep=19mm},"
                r"width=.40\textwidth,height=4.8cm]" + "\n")
        for a, tag in zip(analyzers, files):
            for f, symbol, column in (("rd_mWb", "r_d", "r_d"), ("rq_mWb", "r_q", "r_q")):
                limit = max(float(abs(x.symmetric_pairs[column]).max())*1e3 for x in analyzers)
                title = f"${a.measurement.rotor_temperature:g}$ " + r"$^\circ$C; $"+symbol+r"$ / mWb"
                body += map_panel(tag+"_pairs.dat", f, title, r"$a_q$ / A", limit)
        figure("09_experimental_residuals.tex", body+r"\end{groupplot}",
               r"Forbidden components at all 1172 matched pairs per rotor-reference slice. Color scales are fixed per component across rows and include the full extrema. The horizontal label is the requested d-current key; $a_q$ is the mean measured q-current magnitude of the pair. Local extrema and unmeasured gaps are retained.", "fig:experimental-residuals")
        body = (r"\begin{groupplot}[group style={group size=2 by 2,horizontal sep=32mm,vertical sep=22mm},"
                r"width=.40\textwidth,height=5.2cm]"+"\n")
        limit = max(float(abs(x.symmetric_pairs.delta_R_eq.dropna()).max())*1e3 for x in analyzers)
        for a, tag in zip(analyzers, files):
            title = f"${a.measurement.rotor_temperature:g}$ " + r"$^\circ$C; $\Delta R_{\mathrm{eq}}$ / m$\Omega$"
            body += map_panel(tag+"_valid.dat", "req_mOhm", title, r"$a_q$ / A", limit)
        body += (r"\nextgroupplot[diagnostic axis,width=.35\textwidth,height=4.8cm,title={High-current summary},xlabel={Rotor reference / $^\circ$C},"
                 r"ylabel={Median / m$\Omega$},xmin=30,xmax=90]"+"\n"+
                 r"\addplot[reference samples,error bars/.cd,y dir=both,y explicit] coordinates {"+
                 " ".join(f"({s['rotor_reference_C']},{s['high_equivalent_ohm']['median']*1e3}) +- (0,{s['high_equivalent_ohm']['raw_mad']*1e3})" for s in report["slices"])+"};\n"+r"\end{groupplot}")
        figure("10_experimental_equivalent.tex", body,
               r"Is the resistance-equivalent residual spatially constant? All valid pairs are shown at a common, unclipped color range in m$\Omega$. The last panel summarizes $a_q/a_{q,\max}\geq0.85$ with median and raw MAD bars, which represent descriptive spread rather than confidence intervals. Rotor reference is not winding temperature.", "fig:experimental-equivalent")
        body = (r"\begin{axis}[diagnostic axis,width=.85\textwidth,height=7cm,xlabel={$a_q/a_{q,\max}$},"
                r"ylabel={$\Delta R_{\mathrm{eq}}$ / m$\Omega$},title={Retain the spatial spread},"
                r"legend columns=3,xmin=.1,xmax=1.02]"+"\n")
        for style, a, tag in zip(("reference samples", "measured samples", "only marks,derived quantity,mark=triangle*"), analyzers, files):
            body += r"\addplot["+style+r"] table[x=relative_iq,y=req_mOhm]{figures/data/experimental/"+tag+"_valid.dat};\n"
            body += r"\addlegendentry{"+f"{a.measurement.rotor_temperature:g}"+r" $^\circ$C}"+"\n"
        body += r"\draw[guide quantity,guide pattern] (rel axis cs:.8152173913,0) -- (rel axis cs:.8152173913,1);"+"\n"+r"\end{axis}"
        figure("11_high_current_structure.tex", body,
               r"Each marker is one valid matched pair, projected onto relative measured q-current. The narrower spread near maximum q-current is an empirical feature of this dataset. The guide marks the initial 0.85 summary threshold; it does not define a universal identification region. No outlier removal is used.", "fig:high-current")
    else:
        lo, hi = [int(a.measurement.rpm) for a in analyzers]
        expected = common[f"r_d_{lo}"] * lo/hi
        deviation = common[f"r_d_{hi}"] - expected
        difference = common[f"delta_R_eq_{hi}"]-common[f"delta_R_eq_{lo}"]
        adjusted = expected*common[f"iq_mag_{hi}"]/common[f"iq_mag_{lo}"]
        report["common_speed"] = {
            "pairs": len(common), "direct_scaling_rms_Wb": float(np.sqrt(np.mean(deviation**2))),
            "direct_scaling_median_Wb": float(np.median(deviation)),
            "high_speed_rd_rms_Wb": float(np.sqrt(np.mean(common[f"r_d_{hi}"]**2))),
            "current_adjusted_scaling_rms_Wb": float(np.sqrt(np.mean((common[f"r_d_{hi}"]-adjusted)**2))),
            "equivalent_difference_ohm": robust(difference),
            "equivalent_difference_rms_ohm": float(np.sqrt(np.mean(difference**2))),
            "iq_magnitude_speed_difference_max_A": float(abs(common[f"iq_mag_{hi}"]-common[f"iq_mag_{lo}"]).max())}
        common.to_csv(DATA / "common_speed.csv", index=False)
        scatter = pd.DataFrame({"predicted_mWb": 1e3*expected,
                                "observed_mWb": 1e3*common[f"r_d_{hi}"],
                                "req_low_mOhm": 1e3*common[f"delta_R_eq_{lo}"],
                                "req_high_mOhm": 1e3*common[f"delta_R_eq_{hi}"],
                                "id_key": common.id_key, "iq_key": common.iq_key,
                                "difference_mOhm": 1e3*difference})
        save_dat(scatter, "common_speed.dat")
        body = (r"\begin{groupplot}[group style={group size=2 by 1,horizontal sep=18mm},diagnostic axis,height=6cm]"+"\n"+
                r"\nextgroupplot[title={Direct inverse-speed prediction},xlabel={$r_{d,1000}/3$ / mWb},ylabel={$r_{d,3000}$ / mWb}]"+"\n"+
                r"\addplot[measured samples] table[x=predicted_mWb,y=observed_mWb]{figures/data/experimental/common_speed.dat};"+"\n")
        low = float(min(scatter.predicted_mWb.min(), scatter.observed_mWb.min()))
        high = float(max(scatter.predicted_mWb.max(), scatter.observed_mWb.max()))
        body += r"\addplot[guide quantity,guide pattern,domain="+f"{low}:{high}"+r"] {x};"+"\n"
        body += (r"\nextgroupplot[title={Equivalent residual at common keys},xlabel={$\Delta R_{\mathrm{eq},1000}$ / m$\Omega$},ylabel={$\Delta R_{\mathrm{eq},3000}$ / m$\Omega$}]"+"\n"+
                 r"\addplot[measured samples] table[x=req_low_mOhm,y=req_high_mOhm]{figures/data/experimental/common_speed.dat};"+"\n")
        low = float(min(scatter.req_low_mOhm.min(), scatter.req_high_mOhm.min()))
        high = float(max(scatter.req_low_mOhm.max(), scatter.req_high_mOhm.max()))
        body += r"\addplot[guide quantity,guide pattern,domain="+f"{low}:{high}"+r"] {x};"+"\n"+r"\end{groupplot}"
        figure("12_experimental_scaling.tex", body,
               r"Two pointwise checks on the same 36 common valid keys at a rotor reference of 70 $^\circ$C. Dashed equality lines are the sole constant-resistance-mismatch predictions. The left plot tests the directly observed residual; the right includes the measured pair-current denominator. The systematic spread away from equality cannot be summarized reliably by a single fitted slope.", "fig:experimental-scaling")
        body = (r"\begin{groupplot}[group style={group size=2 by 1,horizontal sep=18mm},diagnostic axis,height=6cm]"+"\n"+
                r"\nextgroupplot[title={Speed and operating-point dependence},xlabel={$a_q/a_{q,\max}$},ylabel={$\Delta R_{\mathrm{eq}}$ / m$\Omega$},legend columns=2]"+"\n")
        for style, a, tag in zip(("reference samples", "measured samples"), analyzers, files):
            body += r"\addplot["+style+r"] table[x=relative_iq,y=req_mOhm]{figures/data/experimental/"+tag+"_valid.dat};\n"
            body += r"\addlegendentry{"+f"{a.measurement.rpm:g} rpm"+"}\n"
        difference_limit = float(abs(scatter.difference_mOhm).max())
        body += (r"\nextgroupplot[sample map axis,width=.38\textwidth,height=6cm,title={Speed difference / m$\Omega$},xlabel={$i_{d,\mathrm{key}}$ / A},ylabel={$|i_{q,\mathrm{key}}|$ / A},point meta min="+
                 f"{-difference_limit},point meta max={difference_limit}"+
                 "]\n"+r"\addplot[sparse sample map] table[x=id_key,y=iq_key,meta=difference_mOhm]{figures/data/experimental/common_speed.dat};"+"\n"+r"\end{groupplot}")
        figure("13_experimental_speed_structure.tex", body,
               r"All 36 valid equivalent-residual pairs at each speed (left), and differences $\Delta R_{\mathrm{eq},3000}-\Delta R_{\mathrm{eq},1000}$ on common keys (right). Separate high-current summaries contain only six and seven pairs. Requested-key matching preserves nominal geometry but does not force identical measured currents.", "fig:experimental-speed-structure")
    report["script_sha256"] = {p.name: hashlib.sha256(p.read_bytes()).hexdigest()
                                for p in (ROOT / "python").glob("*.py")}
    (DATA / f"{experiment}_results.json").write_text(json.dumps(report, indent=2)+"\n", encoding="utf-8")
    print(f"Exported {experiment}: {DATA}")
    if common is not None:
        print(json.dumps(report["common_speed"], indent=2))
